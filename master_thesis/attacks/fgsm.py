import torch
import torch.nn as nn
def fgsm_attack(model,images,labels,eps,device):
    # adv_x = input image + epsilon * sign( gradient of loss w.r.t input image)

    '''
    Fast Gradient Sign Method
    1. Forward pass -> compute the loss
    2. Backward pass -> compute the gradients of the loss w.r.t input image
    3. The sign of the gradient is taken and multiplied by epsilon to create adversarial perturbation
    4. The adversarial example is generated by adding the perturbation to the original image
    
    
    '''
    #input image shoudld be copied and detached from the computation graph to avoid modifying the original image during backpropagation

    original_images= images.clone().detach().to(device)
    original_images.requires_grad = True
    outputs = model(original_images)

    loss = nn.CrossEntropyLoss()(outputs, labels)
    model.zero_grad()
    loss.backward()

    perturbations= eps*torch.sign(original_images.grad.data)
    adv_x = original_images + perturbations
    adv_x = torch.clamp(adv_x, 0, 1)
    
    #return the adversarial example
    return adv_x,perturbations
